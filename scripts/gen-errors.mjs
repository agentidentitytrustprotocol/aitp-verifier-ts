#!/usr/bin/env node
// Generates src/errors.ts from the vendored registries/error-codes.md.
//
//   node scripts/gen-errors.mjs          write src/errors.ts
//   node scripts/gen-errors.mjs --check  fail if src/errors.ts is stale
//
// Every table row whose first cell is a backticked UPPER_SNAKE code is a
// registry entry. A code listed in several tables (INCOMPATIBLE_TRUST_ANCHORS
// is in three) appears once, with the retryable flag of the first table that
// states one; tables that disagree on a code's flag or spec_status fail the
// run instead of picking one.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const REGISTRY = join(ROOT, "vendor", "spec", "registries", "error-codes.md");
const OUT = join(ROOT, "src", "errors.ts");

const cells = (line) => line.trim().replace(/^\|/, "").replace(/\|$/, "").split("|").map((c) => c.trim());

const codes = new Map();
let header = null;
for (const line of readFileSync(REGISTRY, "utf8").split("\n")) {
  if (!line.trim().startsWith("|")) {
    header = null;
    continue;
  }
  const row = cells(line);
  if (row.every((c) => /^:?-+:?$/.test(c))) continue;
  const m = /^`([A-Z][A-Z0-9_]*)`$/.exec(row[0] ?? "");
  if (!m) {
    header = row.map((c) => c.toLowerCase());
    continue;
  }
  if (!header) throw new Error(`table row without header: ${line}`);
  const code = m[1];
  const ri = header.indexOf("retryable");
  const si = header.indexOf("spec_status");
  const retryable = ri === -1 ? null : row[ri] === "true" ? true : row[ri] === "false" ? false : undefined;
  if (retryable === undefined) throw new Error(`${code}: unreadable retryable cell ${row[ri]}`);
  const specStatus = si === -1 ? null : row[si];
  if (specStatus !== null && specStatus !== "core" && specStatus !== "draft") {
    throw new Error(`${code}: unknown spec_status ${specStatus}`);
  }
  const prev = codes.get(code);
  if (!prev) {
    codes.set(code, { retryable, specStatus });
    continue;
  }
  if (retryable !== null) {
    if (prev.retryable !== null && prev.retryable !== retryable) throw new Error(`${code}: tables disagree on retryable`);
    prev.retryable = retryable;
  }
  if (specStatus !== null) {
    if (prev.specStatus !== null && prev.specStatus !== specStatus) throw new Error(`${code}: tables disagree on spec_status`);
    prev.specStatus = specStatus;
  }
}
if (codes.size === 0) throw new Error("no codes parsed from the registry");

const pin = readFileSync(join(ROOT, "SPEC_VERSION"), "utf8").trim();
const entries = [...codes].map(
  ([code, { retryable, specStatus }]) =>
    `  ${code}: { retryable: ${retryable}, specStatus: ${specStatus === null ? "null" : JSON.stringify(specStatus)} },`,
);
const out = `// GENERATED by scripts/gen-errors.mjs from registries/error-codes.md at spec
// ${pin}.
// Do not edit: run \`npm run gen:errors\`. CI fails when this file and the
// registry disagree.

/** Every code in the AITP error-code registry, in registry order. */
export const ERROR_REGISTRY = {
${entries.join("\n")}
} as const;

/** A code from the AITP error-code registry. */
export type ErrorCode = keyof typeof ERROR_REGISTRY;

export function isErrorCode(value: string): value is ErrorCode {
  return Object.prototype.hasOwnProperty.call(ERROR_REGISTRY, value);
}

/** A verification failure carrying exactly one registry code. */
export class AitpError extends Error {
  readonly code: ErrorCode;

  constructor(code: ErrorCode, message: string = code) {
    super(message);
    this.name = "AitpError";
    this.code = code;
  }
}
`;

if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== out) {
    console.error("src/errors.ts is stale against vendor/spec/registries/error-codes.md; run npm run gen:errors");
    process.exit(1);
  }
  console.log(`src/errors.ts matches the registry (${codes.size} codes)`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote src/errors.ts (${codes.size} codes)`);
}
